package api

import (
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"strings"

	"vornik.io/vornik/internal/aimark"
	"vornik.io/vornik/internal/persistence"
	"vornik.io/vornik/internal/ratelimit"
)

// EU AI Act Art 50(2) detection (GitHub #117; Art 50 design §14.9): three
// PUBLIC, read-only routes. They answer whether an exact content was
// generated here and on which day, whether a mark is genuine, and which keys
// sign marks. They never return content, a task, a project or the surface.

const (
	provenancePrefix  = "/provenance/"
	provenanceVerify  = "/provenance/verify"
	aiMarkKeysPath    = "/.well-known/vornik-ai-mark-keys"
	detectRPS         = 5
	detectBurst       = 10
	detectBodyCap     = 16 << 10
	notConfiguredText = "AI output marking is not configured on this instance."
)

// WithAIMarkLedger sets the marks ledger the detection routes read; without
// one they answer 503.
func WithAIMarkLedger(l persistence.AIOutputMarkRepository) ServerOption {
	return func(s *Server) { s.aiMarkLedger = l }
}

// detectGuard applies the rate limit and the configured check, and reports
// whether the handler may go on. Public endpoint: AuthMiddleware did not
// limit this request.
func (s *Server) detectGuard(w http.ResponseWriter, r *http.Request) bool {
	// The routes' own per-IP limiter: public routes skip AuthMiddleware's,
	// and enforcePerIPRateLimit does nothing without one, so this cannot
	// depend on configuration (§14.9 B).
	s.detectLimiterOnce.Do(func() { s.detectLimiter = ratelimit.NewPerIPLimiter() })
	if enforcePerIPRateLimit(w, r, s.detectLimiter, nil, detectRPS, detectBurst) {
		return false
	}
	w.Header().Set("Cache-Control", "no-store")
	if s.aiMarkLedger == nil {
		respondJSON(w, http.StatusServiceUnavailable, map[string]any{"statement": notConfiguredText})
		return false
	}
	return true
}

// registerAIMarkDetection mounts the three routes.
func (s *Server) registerAIMarkDetection(mux *http.ServeMux) {
	mux.HandleFunc(provenanceVerify, s.ProvenanceVerify)
	mux.HandleFunc(provenancePrefix, s.ProvenanceLookup)
	mux.HandleFunc(aiMarkKeysPath, s.AIMarkKeys)
}

// ProvenanceLookup is GET /provenance/{sha256}.
func (s *Server) ProvenanceLookup(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		w.Header().Set("Allow", http.MethodGet)
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	if !s.detectGuard(w, r) {
		return
	}
	h := strings.TrimPrefix(r.URL.Path, provenancePrefix)
	if !isSHA256Hex(h) {
		respondJSON(w, http.StatusBadRequest, map[string]any{"statement": "Give the content's SHA-256 as 64 lowercase hex characters."})
		return
	}
	m, err := s.aiMarkLedger.Get(r.Context(), h)
	if errors.Is(err, persistence.ErrNotFound) {
		respondJSON(w, http.StatusOK, map[string]any{"found": false, "statement": "No record of this content."})
		return
	}
	if err != nil || m == nil {
		respondJSON(w, http.StatusServiceUnavailable, map[string]any{"statement": "The record could not be read; try again later."})
		return
	}
	day := m.IssuedAt.UTC().Format("2006-01-02")
	respondJSON(w, http.StatusOK, map[string]any{
		"found":     true,
		"statement": "Generated by an AI system operated with Vornik on " + day + ".",
		"issued":    day,
	})
}

// ProvenanceVerify is POST /provenance/verify {"mark", "sha256"?}.
func (s *Server) ProvenanceVerify(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		w.Header().Set("Allow", http.MethodPost)
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	if !s.detectGuard(w, r) {
		return
	}
	var req struct {
		Mark   string `json:"mark"`
		SHA256 string `json:"sha256"`
	}
	body, err := io.ReadAll(io.LimitReader(r.Body, detectBodyCap+1))
	if err != nil || len(body) > detectBodyCap {
		respondJSON(w, http.StatusRequestEntityTooLarge, map[string]any{"statement": "The request is too large."})
		return
	}
	if err := json.Unmarshal(body, &req); err != nil || req.Mark == "" {
		respondJSON(w, http.StatusBadRequest, map[string]any{"statement": `Send {"mark": "<the mark>"}.`})
		return
	}
	rows, err := s.aiMarkLedger.Keys(r.Context())
	if err != nil {
		respondJSON(w, http.StatusServiceUnavailable, map[string]any{"statement": "The keys could not be read; try again later."})
		return
	}
	m, err := aimark.Verify(req.Mark, aimark.KeysFrom(rows))
	if err != nil {
		// No detail on which part failed: no oracle for refining a forgery.
		respondJSON(w, http.StatusOK, map[string]any{"valid": false, "statement": "This mark does not verify."})
		return
	}
	issued := m.IAT
	if len(issued) >= 10 {
		issued = issued[:10]
	}
	out := map[string]any{
		"valid":       true,
		"statement":   "This mark is genuine: content generated by an AI system operated with Vornik on " + issued + ".",
		"generator":   m.Gen,
		"source_type": m.Src,
		"issued":      issued,
		"key_id":      m.KID,
	}
	if req.SHA256 != "" {
		out["matches"] = strings.EqualFold(req.SHA256, m.SHA256)
	}
	respondJSON(w, http.StatusOK, out)
}

// AIMarkKeys is GET /.well-known/vornik-ai-mark-keys. A key is valid from its
// first use until the next key's (the table records no retirement).
func (s *Server) AIMarkKeys(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		w.Header().Set("Allow", http.MethodGet)
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	if !s.detectGuard(w, r) {
		return
	}
	rows, err := s.aiMarkLedger.Keys(r.Context())
	if err != nil {
		respondJSON(w, http.StatusServiceUnavailable, map[string]any{"statement": "The keys could not be read; try again later."})
		return
	}
	keys := make([]map[string]string, 0, len(rows))
	for i, k := range rows {
		until := ""
		if i+1 < len(rows) {
			until = rows[i+1].FirstUsedAt.UTC().Format("2006-01-02T15:04:05Z")
		}
		keys = append(keys, map[string]string{
			"kid":         k.KID,
			"alg":         "Ed25519",
			"public_key":  aimark.EncodeKey(k.PublicKey),
			"valid_from":  k.FirstUsedAt.UTC().Format("2006-01-02T15:04:05Z"),
			"valid_until": until,
		})
	}
	respondJSON(w, http.StatusOK, map[string]any{"keys": keys})
}

func isSHA256Hex(h string) bool {
	if len(h) != 64 {
		return false
	}
	for _, c := range h {
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}
