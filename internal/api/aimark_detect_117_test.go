type detectLedger struct {
	marks map[string]persistence.AIOutputMark
	keys  []persistence.AIMarkKey
}

func (l *detectLedger) Record(_ context.Context, m persistence.AIOutputMark) error {
	if _, ok := l.marks[m.ContentSHA256]; !ok {
		l.marks[m.ContentSHA256] = m
	}
	return nil
}
func (l *detectLedger) Get(_ context.Context, h string) (*persistence.AIOutputMark, error) {
	m, ok := l.marks[h]
	if !ok {
		return nil, persistence.ErrNotFound
	}
	return &m, nil
}
func (l *detectLedger) RecordKey(_ context.Context, k persistence.AIMarkKey) error {
	l.keys = append(l.keys, k)
	return nil
}
func (l *detectLedger) Keys(context.Context) ([]persistence.AIMarkKey, error) { return l.keys, nil }

func sum(s string) string { h := sha256.Sum256([]byte(s)); return hex.EncodeToString(h[:]) }

// detectFixture: two keys (k1 older), one recorded output signed by each.
func detectFixture(t *testing.T) (*Server, *detectLedger, string, string) {
	t.Helper()
	l := &detectLedger{marks: map[string]persistence.AIOutputMark{}}
	old, cur := aimark.NewSigner(bytes.Repeat([]byte{1}, 32)), aimark.NewSigner(bytes.Repeat([]byte{2}, 32))
	t0 := time.Date(2026, 11, 1, 9, 0, 0, 0, time.UTC)
	_ = l.RecordKey(context.Background(), persistence.AIMarkKey{KID: old.KID(), PublicKey: old.PublicKey(), FirstUsedAt: t0})
	_ = l.RecordKey(context.Background(), persistence.AIMarkKey{KID: cur.KID(), PublicKey: cur.PublicKey(), FirstUsedAt: t0.Add(time.Hour)})
	oldMark, _, _ := aimark.NewMarker(old, l, func() string { return "r" }, nil, nil).New(context.Background(), []byte("old reply"), "email", "task_secret_1")
	curMark, _, _ := aimark.NewMarker(cur, l, func() string { return "r" }, nil, nil).New(context.Background(), []byte("new reply"), "telegram", "task_secret_2")
	return NewServer(WithAIMarkLedger(l)), l, oldMark, curMark
}

func call(t *testing.T, h http.HandlerFunc, method, path, body string) (int, map[string]any, string) {
	t.Helper()
	rr := httptest.NewRecorder()
	h(rr, httptest.NewRequest(method, path, strings.NewReader(body)))
	var out map[string]any
	_ = json.Unmarshal(rr.Body.Bytes(), &out)
	return rr.Code, out, rr.Body.String()
}

func TestProvenance117_Lookup(t *testing.T) {
	s, _, _, _ := detectFixture(t)
	code, out, raw := call(t, s.ProvenanceLookup, http.MethodGet, "/provenance/"+sum("new reply"), "")
	if code != 200 || out["found"] != true || !strings.Contains(out["statement"].(string), "Generated by an AI system") {
		t.Fatalf("found: %d %s", code, raw)
	}
	for _, leak := range []string{"task_secret", "telegram", "mark"} {
		if strings.Contains(raw, leak) {
			t.Errorf("lookup reveals %q: %s", leak, raw)
		}
	}
	if code, out, _ = call(t, s.ProvenanceLookup, http.MethodGet, "/provenance/"+sum("never generated"), ""); code != 200 || out["found"] != false {
		t.Errorf("miss: %d %v", code, out)
	}
	for _, bad := range []string{"xyz", strings.Repeat("A", 64), strings.Repeat("a", 63)} {
		if code, _, _ := call(t, s.ProvenanceLookup, http.MethodGet, "/provenance/"+bad, ""); code != 400 {
			t.Errorf("hash %q: %d, want 400", bad, code)
		}
	}
}

func TestProvenance117_Verify(t *testing.T) {
	s, _, oldMark, curMark := detectFixture(t)
	for name, m := range map[string]string{"current key": curMark, "older key": oldMark} {
		body, _ := json.Marshal(map[string]string{"mark": m})
		code, out, raw := call(t, s.ProvenanceVerify, http.MethodPost, "/provenance/verify", string(body))
		if code != 200 || out["valid"] != true || out["source_type"] != aimark.DigitalSourceType {
			t.Errorf("%s: %d %s", name, code, raw)
		}
		if strings.Contains(raw, "task_secret") || strings.Contains(raw, "surface") {
			t.Errorf("%s: verify reveals more than it should: %s", name, raw)
		}
	}
	body, _ := json.Marshal(map[string]string{"mark": curMark, "sha256": sum("new reply")})
	if _, out, _ := call(t, s.ProvenanceVerify, http.MethodPost, "/provenance/verify", string(body)); out["matches"] != true {
		t.Errorf("matching hash: %v", out)
	}
	body, _ = json.Marshal(map[string]string{"mark": curMark, "sha256": sum("other")})
	if _, out, _ := call(t, s.ProvenanceVerify, http.MethodPost, "/provenance/verify", string(body)); out["matches"] != false {
		t.Errorf("other hash: %v", out)
	}
	// Flip a signature character to a DIFFERENT one: a fixed replacement
	// ("AA") left the mark untouched when the random key's signature already
	// ended that way, about one run in 256.
	flip := byte('A')
	if curMark[len(curMark)-3] == 'A' {
		flip = 'B'
	}
	tampered := curMark[:len(curMark)-3] + string(flip) + curMark[len(curMark)-2:]
	body, _ = json.Marshal(map[string]string{"mark": tampered})
	if code, out, _ := call(t, s.ProvenanceVerify, http.MethodPost, "/provenance/verify", string(body)); code != 200 || out["valid"] != false || out["statement"] != "This mark does not verify." {
		t.Errorf("tampered: %d %v", code, out)
	}
	if code, _, _ := call(t, s.ProvenanceVerify, http.MethodPost, "/provenance/verify", `{"mark":"`+strings.Repeat("a", 20000)+`"}`); code != http.StatusRequestEntityTooLarge && code != 400 {
		t.Errorf("oversized body: %d", code)
	}
}

func TestProvenance117_Keys(t *testing.T) {
	s, l, _, _ := detectFixture(t)
	code, out, _ := call(t, s.AIMarkKeys, http.MethodGet, "/.well-known/vornik-ai-mark-keys", "")
	keys, _ := out["keys"].([]any)
	if code != 200 || len(keys) != 2 {
		t.Fatalf("keys: %d %v", code, out)
	}
	k0, k1 := keys[0].(map[string]any), keys[1].(map[string]any)
	if k0["kid"] != l.keys[0].KID || k0["alg"] != "Ed25519" || k0["valid_until"] != k1["valid_from"] || k1["valid_until"] != "" {
		t.Errorf("validity not derived: %v", keys)
	}
	empty := NewServer(WithAIMarkLedger(&detectLedger{marks: map[string]persistence.AIOutputMark{}}))
	if code, out, _ := call(t, empty.AIMarkKeys, http.MethodGet, "/.well-known/vornik-ai-mark-keys", ""); code != 200 || len(out["keys"].([]any)) != 0 {
		t.Errorf("empty: %d %v", code, out)
	}
}

