func TestProvenance117_PublicAndRateLimited(t *testing.T) {
	s, _, _, _ := detectFixture(t)
	cfg := &config.Config{}
	cfg.API.AuthEnabled = true
	mux := http.NewServeMux()
	s.registerAIMarkDetection(mux)
	h := AuthMiddleware(BuildAuthConfig(cfg))(mux)
	path := "/provenance/" + sum("new reply")
	codes := map[int]int{}
	for i := 0; i < 11; i++ {
		rr := httptest.NewRecorder()
		req := httptest.NewRequest(http.MethodGet, path, nil)
		req.RemoteAddr = "203.0.113.7:4000"
		h.ServeHTTP(rr, req)
		codes[rr.Code]++
	}
	if codes[200] != 10 || codes[http.StatusTooManyRequests] != 1 {
		t.Fatalf("without credentials, burst 10: got %v, want ten 200s and one 429", codes)
	}
	rr := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodGet, "/.well-known/vornik-ai-mark-keys", nil)
	req.RemoteAddr = "198.51.100.9:4000"
	h.ServeHTTP(rr, req)
	if rr.Code != 200 {
		t.Fatalf("keys without credentials: %d", rr.Code)
	}
}

