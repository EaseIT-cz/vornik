package docrender

// EU AI Act Art 50(2) marking of rendered documents (GitHub #117; Art 50
// design §14.8, commit 5). Pandoc carries these metadata fields into HTML
// <meta> tags, the PDF Info Subject and Keywords (through WeasyPrint), and
// DOCX core and custom properties (measured 2026-11-01, pandoc 3.1.3,
// WeasyPrint 61.1).

// AIGeneratedDescription states what the document is, in every format.
const AIGeneratedDescription = "AI-generated by Vornik (EU AI Act Art 50(2), IPTC trainedAlgorithmicMedia)."

var markKeywords = []string{"trainedAlgorithmicMedia", "vornik-ai-mark"}

// MarkMeta adds the marking fields to a pandoc metadata map. compact is the
// signed mark over the document's markdown source, or "" where no signer is
// available, which leaves the statement unsigned.
func MarkMeta(meta map[string]any, compact string) {
	meta["description"] = AIGeneratedDescription
	meta["keywords"] = markKeywords
	if compact != "" {
		meta["description"] = AIGeneratedDescription + " vornik-ai-mark: " + compact
		meta["vornik-ai-mark"] = compact
	}
}

// UnsignedMarkArgs are the same fields as pandoc arguments, for a renderer
// with no signer (the agent container's document_render).
func UnsignedMarkArgs() []string {
	args := []string{"--metadata=description:" + AIGeneratedDescription}
	for _, k := range markKeywords {
		args = append(args, "--metadata=keywords:"+k)
	}
	return args
}
