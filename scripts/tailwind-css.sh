#!/usr/bin/env bash
# tailwind-css.sh — generate, or check, the console stylesheet
# internal/ui/static/tailwind.css with the pinned standalone Tailwind CLI.
#
#   scripts/tailwind-css.sh           regenerate the committed file (make ui-css)
#   scripts/tailwind-css.sh --check   regenerate into a temp file and fail if it
#                                     differs from the committed one (make ui-css-check)
#
# Design: https://docs.vornik.io "Self-hosted Tailwind and the
# console CSP — 2026-10-16" (GitHub #165). The console used to load the Tailwind
# Play CDN script from cdn.tailwindcss.com on every page.
#
# The CLI is fetched once into ${XDG_CACHE_HOME:-$HOME/.cache}/vornik/tools/
# (or taken from $TAILWINDCSS_BIN) and its SHA-256 is verified against the pin
# below on EVERY run, not only after a download: a binary that does not match
# is refused and never executed. The pins come from the v3.4.17 release's
# sha256sums.txt (trust on first use, pinned here so a later change upstream is
# detected).
set -euo pipefail

TAILWIND_VERSION=v3.4.17

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
config="$repo_root/internal/ui/tailwind/tailwind.config.js"
input="$repo_root/internal/ui/tailwind/input.css"
output="$repo_root/internal/ui/static/tailwind.css"
header="/* Generated by scripts/tailwind-css.sh (Tailwind CSS $TAILWIND_VERSION) from internal/ui/tailwind/. Do not edit; run make ui-css. */"

mode=generate
case "${1:-}" in
  "") ;;
  --check) mode=check ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

# asset_for prints the release asset name for this host.
asset_for() {
  local os arch
  os=$(uname -s); arch=$(uname -m)
  case "$os/$arch" in
    Linux/x86_64) echo tailwindcss-linux-x64 ;;
    Linux/aarch64|Linux/arm64) echo tailwindcss-linux-arm64 ;;
    Darwin/x86_64) echo tailwindcss-macos-x64 ;;
    Darwin/arm64) echo tailwindcss-macos-arm64 ;;
    *) echo "tailwind-css: no pinned Tailwind CLI for $os/$arch" >&2; return 1 ;;
  esac
}

# pinned_sha256 prints the pinned checksum of an asset.
pinned_sha256() {
  case "$1" in
    tailwindcss-linux-x64)   echo 7d24f7fa191d2193b78cd5f5a42a6093e14409521908529f42d80b11fde1f1d4 ;;
    tailwindcss-linux-arm64) echo 69b1378b8133192d7d2feb12a116fa12d035594f58db3eff215879e4ad8cf39b ;;
    tailwindcss-macos-x64)   echo 6cbdad74be776c087ffa5e9a057512c54898f9fe8828d3362212dfe32fc933a3 ;;
    tailwindcss-macos-arm64) echo a1d0c7985759accca0bf12e51ac1dcbf0f6cf2fffb62e6e0f62d091c477a10a3 ;;
    *) return 1 ;;
  esac
}

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

asset=$(asset_for)
want=$(pinned_sha256 "$asset")

if [ -n "${TAILWINDCSS_BIN:-}" ]; then
  bin=$TAILWINDCSS_BIN
else
  cache="${XDG_CACHE_HOME:-$HOME/.cache}/vornik/tools"
  bin="$cache/$asset-$TAILWIND_VERSION"
  if [ ! -f "$bin" ]; then
    mkdir -p "$cache"
    url="https://github.com/tailwindlabs/tailwindcss/releases/download/$TAILWIND_VERSION/$asset"
    echo "tailwind-css: fetching $url" >&2
    if ! curl -fsSL --retry 2 -o "$bin.part" "$url"; then
      rm -f "$bin.part"
      echo "tailwind-css: FAIL — cannot fetch the Tailwind CLI ($url). It is needed once per host; the check is not skipped offline, because a skipped check reads as a pass." >&2
      exit 1
    fi
    mv "$bin.part" "$bin"
  fi
fi

if [ ! -f "$bin" ]; then
  echo "tailwind-css: FAIL — $bin does not exist" >&2
  exit 1
fi
# Under the tools cache, not $TMPDIR: /tmp is often mounted noexec.
tools="${XDG_CACHE_HOME:-$HOME/.cache}/vornik/tools"
mkdir -p "$tools"
tmp=$(mktemp -d "$tools/run.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
# Verify and run a private copy, so the file that runs is the file that was
# checked (no swap between the check and the exec), and $TAILWINDCSS_BIN is
# never modified.
cp "$bin" "$tmp/tailwindcss"
got=$(sha256_of "$tmp/tailwindcss")
if [ "$got" != "$want" ]; then
  echo "tailwind-css: FAIL — $bin has sha256 $got, want $want ($asset $TAILWIND_VERSION). Refusing to run it; delete it to re-fetch." >&2
  exit 1
fi
chmod +x "$tmp/tailwindcss"

# The CLI resolves content globs relative to the config (relative: true), so
# the result does not depend on the working directory.
"$tmp/tailwindcss" -c "$config" -i "$input" -o "$tmp/out.css" --minify >"$tmp/log" 2>&1 || {
  cat "$tmp/log" >&2
  echo "tailwind-css: FAIL — the Tailwind CLI failed" >&2
  exit 1
}
{ echo "$header"; cat "$tmp/out.css"; echo; } >"$tmp/tailwind.css"

if [ "$mode" = generate ]; then
  cp "$tmp/tailwind.css" "$output"
  echo "tailwind-css: wrote ${output#"$repo_root"/} ($(wc -c <"$output" | tr -d ' ') bytes)"
  exit 0
fi

if [ ! -f "$output" ]; then
  echo "ui-css-check: FAIL — ${output#"$repo_root"/} is missing; run make ui-css and commit it." >&2
  exit 1
fi
if ! cmp -s "$tmp/tailwind.css" "$output"; then
  echo "ui-css-check: FAIL — ${output#"$repo_root"/} is stale against its sources (templates, internal/ui Go files, internal/ui/tailwind/). Run make ui-css and commit the result; never edit it by hand." >&2
  diff <(tr '}' '\n' <"$output") <(tr '}' '\n' <"$tmp/tailwind.css") | sed -n 1,20p >&2 || true
  exit 1
fi
echo "ui-css-check: OK — ${output#"$repo_root"/} matches its sources (Tailwind CSS $TAILWIND_VERSION)."
